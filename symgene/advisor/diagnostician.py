from __future__ import annotations
import json
from dataclasses import dataclass, field
from typing import Any
from symgene.advisor.monitor import MonitorSnapshot

VALID_ACTIONS = {
    "genetic_rescue",
    "adjust_parameters",
    "adjust_mutation_rate",   # legacy alias — maps to adjust_parameters
    "force_migration",
    "restart_worst",
    "suggest_primitive",
    "suggest_early_stop",
}

_SYSTEM_PROMPT = """\
You are SymGene Advisor, an expert AI system guiding a symbolic regression search \
via multi-gene genetic programming (MGGP).

Your task: study the evolutionary state below and choose the single most effective intervention.
Use the `reasoning` field to think step-by-step before committing to an action.
Be creative, context-aware, and strategic — do not default to the same action every time.

════════════════════════════════════════
  AVAILABLE ACTIONS
════════════════════════════════════════

genetic_rescue
  What it does: replaces the worst individuals with new expressions generated by an LLM, \
guided by the structure of the best individuals and their gene coefficients.
  Best when: the population is structurally trapped — best expressions keep recycling the \
same building blocks, or val_r2 stagnates despite reasonable diversity.
  Params: {"rescue_fraction": 0.1–0.3, "level": "gene" (replace one gene per individual) \
or "individual" (replace all genes)}
  Tip: use "gene" when the best individual has some good genes to preserve. Use "individual" \
when the whole population needs fresh structure.

adjust_parameters
  What it does: changes evolutionary hyperparameters to shift the search dynamics.
  Best when: stagnation is algorithmic — selection pressure too high, elites dominating, \
not enough perturbation — not a structural problem.
  Params (any combination, all optional):
    "mutpb"          : 0.05–0.5   — mutation probability (higher = more random perturbation)
    "cxpb"           : 0.5–0.98   — crossover probability
    "cxpb_low"       : 0.1–0.9    — proportion of subtree vs whole-gene crossover
    "tournament_size": 2–10       — LOWER = weaker selection pressure = more diversity
    "elite_ratio"    : 0.01–0.10  — LOWER = elites have less lock-in effect on the gene pool
  Key intuitions:
    - tournament_size is the most powerful lever: reducing from 5→2 dramatically increases exploration
    - low elite_ratio prevents a few dominant individuals from steering the whole population
    - high mutpb shakes the population harder; combine with lower tournament_size for full exploration mode
    - adjusting cxpb_low toward 0.2 favors whole-gene swaps (structural diversity)
  You can adjust multiple parameters at once for a compound effect.

restart_worst
  What it does: reinitializes the worst individuals with random trees. No LLM cost.
  Best when: quick diversity injection; or genetic_rescue was already tried and didn't help. \
Also good when overfitting is detected (randomizing oversimplifies the bad individuals).
  Params: {"fraction": 0.1–0.3}

suggest_primitive
  What it does: proposes a new mathematical primitive based on patterns in the best individuals. \
The primitive is added to the pset immediately, becoming available in future tree generation and mutation.
  Best when: the best individuals repeatedly compose the same sub-expression (e.g. log inside pow, \
or a ratio that appears in every top gene) — naming it as a primitive shortens search path.
  Params:
    "name"             : unique short identifier (no spaces, no special chars)
    "lambda_str"       : valid Python, e.g. "lambda x: math.log(abs(x) + 1e-9) ** (-2)"
    "arity"            : 1 or 2
    "description"      : what it computes and why it might help the search
    "remove_primitive" : name of a primitive absent from top individuals (just a suggestion, logged)
  STRICT RULE: lambda_str may only use: math.log, math.sqrt, math.exp, math.sin, math.cos, \
math.fabs, abs, min, max, pow — nothing else. Must be a single lambda expression.
  Example for Gnielinski: suggest "friction_factor" = \
lambda Re: (0.79 * math.log(abs(Re) + 1e-9) - 1.64) ** (-2)

suggest_early_stop
  What it does: signals that the model has converged satisfactorily.
  Only use if: val_r2 >= 0.99, OR if the last 5+ interventions produced zero improvement.
  Params: {}

════════════════════════════════════════
  HOW TO REASON (follow these steps)
════════════════════════════════════════

1. INTERVENTION HISTORY: Look at what was already tried. If the same action was used 2+ times in \
a row without val_r2 improvement, you MUST choose a different action — repetition is waste.

2. TOP INDIVIDUALS: Study the top-3 individuals and their gene coefficients. High |coef| genes \
carry most of the predictive power. What structures do they share? Are there sub-expressions \
that appear repeatedly? If log, pow, sqrt appear together in every high-coef gene, that's a signal \
for suggest_primitive.

3. PRIMITIVE USAGE: Primitives with 0 count in top individuals are unused dead weight. Primitives \
that dominate (>60% of all nodes) signal a structural attractor. Consider suggest_primitive when \
the pset seems insufficient.

4. CURRENT PARAMETERS: High tournament_size (≥5) creates strong selection pressure that can \
lock in bad solutions. High elite_ratio means elites dominate the gene pool. These are the first \
things to change when diversity collapses or the population stagnates algorithmically.

5. VAL_R2 PATTERN:
   - STAGNATING long-term (>10 gens, delta < 0.01): structural attractor → genetic_rescue or \
suggest_primitive
   - DEGRADING: overfitting → restart_worst or reduce elite_ratio
   - IMPROVING slowly: patience, or gentle parameter nudge

6. ESCALATION: If genetic_rescue was tried twice with no val_r2 improvement, the current pset \
may be insufficient — consider suggest_primitive or a strong parameter change \
(e.g. tournament_size→2, elite_ratio→0.01).

════════════════════════════════════════
  OUTPUT FORMAT — respond ONLY with valid JSON
════════════════════════════════════════

TOKEN BUDGET IS TIGHT. Rules to avoid truncation:
- Put recommended_action and action_params FIRST (most critical fields)
- reasoning: max 1-2 short sentences, no bullet points
- advisor_message: max 1-2 sentences
- root_cause: max 10 words

{
  "recommended_action": "<exact action name>",
  "action_params": {<params for the chosen action>},
  "root_cause": "<max 10 words>",
  "severity": "low|medium|high",
  "confidence": 0.0-1.0,
  "reasoning": "<1-2 sentences only>",
  "advisor_message": "<1-2 sentences only>"
}"""


def _fmt_top_individuals(top: list[dict]) -> str:
    if not top:
        return "  (none available)"
    lines = []
    for rank, ind in enumerate(top, 1):
        fit_str = f"{ind['fitness']:.6f}" if ind.get('fitness') is not None else "?"
        lines.append(f"  ── Rank {rank} | fitness={fit_str} | n_genes={ind.get('n_genes', '?')} ──")
        bias = ind.get('bias')
        for g in ind.get('genes', []):
            coef_str = f"  [coef={g['coef']:+.4f}]" if 'coef' in g else ""
            expr_short = g['expr'][:140]
            lines.append(f"    gene({g['len']} nodes): {expr_short}{coef_str}")
        if bias is not None:
            lines.append(f"    bias: {bias:.4f}")
    return "\n".join(lines)


def _fmt_primitive_usage(usage: dict, available: list) -> str:
    if not usage:
        return "  (no data)"
    unused = sorted(p for p in available if p not in usage)
    sorted_used = sorted(usage.items(), key=lambda kv: kv[1], reverse=True)
    parts = [f"{name}({count})" for name, count in sorted_used]
    line = "  In top-10 → " + ", ".join(parts)
    if unused:
        line += f"\n  NEVER used in top-10: {unused}  ← candidates for removal/replacement"
    return line


def _fmt_intervention_history(history: list[dict]) -> str:
    if not history:
        return "  (no prior interventions)"
    lines = []
    for ev in history:
        status = ev.get('status', '?')
        action = ev.get('action', ev.get('recommended_action', '?'))
        gen = ev.get('gen', '?')
        n = ev.get('n_affected', '?')
        changes = ev.get('changes', {})
        line = f"  gen={gen:<4} | {action:<22} | status={status} | n_affected={n}"
        if changes:
            change_strs = [f"{k}:{v['from']}→{v['to']}" for k, v in changes.items()]
            line += f" | changes=[{', '.join(change_strs)}]"
        reasoning_hint = ev.get('root_cause', '')
        if reasoning_hint:
            line += f" | cause={reasoning_hint}"
        lines.append(line)
    return "\n".join(lines)


def _build_prompt(snapshot: MonitorSnapshot) -> str:
    val_r2_line = (
        f"  val_r2_now      : {snapshot.val_r2:.6f}"
        if snapshot.val_r2 is not None
        else "  val_r2_now      : not available"
    )

    vr_hist = snapshot.val_r2_history_last_10
    if len(vr_hist) >= 2:
        delta = vr_hist[-1] - vr_hist[0]
        if abs(delta) < 0.005:
            trend_label = "STAGNATING"
        elif delta > 0:
            trend_label = "IMPROVING"
        else:
            trend_label = "DEGRADING"
        val_r2_trend_line = (
            f"  val_r2_trend    : {trend_label} ({delta:+.4f} over last {len(vr_hist)} gens)\n"
            f"  val_r2_history  : {[round(v, 4) for v in vr_hist]}"
        )
    else:
        val_r2_trend_line = "  val_r2_trend    : insufficient history"

    param_lines = "\n".join(
        f"  {k:<18}: {v}" for k, v in snapshot.current_params.items()
    )

    sections = [
        f"╔══ POPULATION '{snapshot.pop_name}' | Generation {snapshot.gen} ══╗",
        "",
        "── Fitness & Convergence ──────────────────────────────",
        f"  best_train_fitness : {snapshot.best_fitness:.6e}",
        f"  stagnation_counter : {snapshot.stagnation_counter} gens without improvement in train fitness",
        val_r2_line,
        val_r2_trend_line,
        f"  fitness_variance   : {snapshot.fitness_variance:.6f}",
        f"  recent_fitness (last 10): {[round(v, 6) for v in snapshot.fitness_history_last_30[-10:]]}",
        "",
        "── Population Health ──────────────────────────────────",
        f"  diversity_index  : {snapshot.diversity_index:.3f}  (1.0 = fully diverse, 0.0 = collapsed)",
        f"  complexity_trend : {snapshot.complexity_trend:+.3f}  (positive = trees growing in size)",
        f"  n_genes_best     : {snapshot.n_genes_best}",
        "",
        "── Current Evolutionary Parameters ───────────────────",
        param_lines,
        "",
        "── Top-3 Individuals (HoF) with Gene Coefficients ───",
        _fmt_top_individuals(snapshot.top_individuals),
        "",
        "── Primitive Usage in Top-10 Individuals ─────────────",
        _fmt_primitive_usage(snapshot.primitive_usage, snapshot.available_primitives),
        "",
        "── Intervention History (oldest → newest) ────────────",
        _fmt_intervention_history(snapshot.intervention_history),
        "",
        "╚══ END SNAPSHOT ══╝",
        "",
        "Now diagnose and recommend the best intervention. Use your `reasoning` field to think.",
    ]

    return "\n".join(sections)


@dataclass
class Diagnosis:
    root_cause: str
    severity: str
    confidence: float
    recommended_action: str
    action_params: dict[str, Any]
    advisor_message: str
    reasoning: str = ""


def _repair_truncated_json(text: str) -> str:
    """Best-effort repair of a JSON string truncated mid-stream.
    Closes any open string, then closes any open arrays/objects in reverse order.
    """
    # Track nesting depth (outside strings)
    stack = []
    in_str = False
    escape_next = False
    for ch in text:
        if escape_next:
            escape_next = False
            continue
        if ch == '\\' and in_str:
            escape_next = True
            continue
        if ch == '"':
            in_str = not in_str
            continue
        if not in_str:
            if ch in ('{', '['):
                stack.append('}' if ch == '{' else ']')
            elif ch in ('}', ']') and stack:
                stack.pop()

    closing = ""
    if in_str:
        closing += '"'   # close the open string
    # strip trailing comma if any
    tail = (text + closing).rstrip()
    if tail.endswith(','):
        tail = tail[:-1]
    # close open structures in reverse
    tail += "".join(reversed(stack))
    return tail


def _parse_response(raw: str) -> Diagnosis:
    text = raw.strip()
    if text.startswith("```"):
        parts = text.split("```")
        text = parts[1] if len(parts) > 1 else text
        if text.startswith("json"):
            text = text[4:]
        text = text.strip()

    # First try: parse as-is
    data: dict = {}
    try:
        data = json.loads(text)
    except json.JSONDecodeError:
        # Second try: repair truncated JSON
        try:
            data = json.loads(_repair_truncated_json(text))
        except json.JSONDecodeError:
            # Third try: extract just the action fields with regex fallback
            import re
            action_match = re.search(r'"recommended_action"\s*:\s*"([^"]+)"', text)
            if action_match:
                data = {"recommended_action": action_match.group(1)}
            # if nothing works, data stays {} and we fall through to defaults

    action = data.get("recommended_action", "genetic_rescue")
    if action not in VALID_ACTIONS:
        action = "genetic_rescue"

    return Diagnosis(
        root_cause=data.get("root_cause", "unknown"),
        severity=data.get("severity", "medium"),
        confidence=float(data.get("confidence", 0.5)),
        recommended_action=action,
        action_params=data.get("action_params", {}),
        advisor_message=str(data.get("advisor_message", "")),
        reasoning=str(data.get("reasoning", "")),
    )


class Diagnostician:
    def __init__(self, client: Any) -> None:
        self.client = client

    def diagnose(self, snapshot: MonitorSnapshot) -> Diagnosis:
        prompt = _build_prompt(snapshot)
        raw = self.client.complete(prompt, system=_SYSTEM_PROMPT)
        return _parse_response(raw)
